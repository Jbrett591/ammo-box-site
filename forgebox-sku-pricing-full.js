const forgeboxSkuPricing = {};

forgeboxRawPricingData.forEach(([caliber, capacity, grams, totalCost, wholesalePrice, retailPrice]) => {
  const cleanCaliber = normalizeSkuText(caliber);
  const cleanCapacity = Number(capacity);

  if (!forgeboxSkuPricing[cleanCaliber]) {
    forgeboxSkuPricing[cleanCaliber] = {};
  }

  forgeboxSkuPricing[cleanCaliber][cleanCapacity] = {
    caliber,
    capacity: cleanCapacity,
    grams: Number(grams),
    totalCost: Number(totalCost),
    wholesalePrice: Number(wholesalePrice),
    retailPrice: Number(retailPrice)
  };
});

function getSkuPrice(category, caliber, capacity) {
  const cleanCaliber = normalizeSkuText(caliber);
  const cleanCapacity = Number(capacity);
  return forgeboxSkuPricing?.[cleanCaliber]?.[cleanCapacity]?.retailPrice ?? 25;
}

function getSkuWholesalePrice(category, caliber, capacity) {
  const cleanCaliber = normalizeSkuText(caliber);
  const cleanCapacity = Number(capacity);
  return forgeboxSkuPricing?.[cleanCaliber]?.[cleanCapacity]?.wholesalePrice ?? 18;
}

function getSkuCostInfo(category, caliber, capacity) {
  const cleanCaliber = normalizeSkuText(caliber);
  const cleanCapacity = Number(capacity);
  return forgeboxSkuPricing?.[cleanCaliber]?.[cleanCapacity] ?? null;
}

function hasSkuPrice(category, caliber, capacity) {
  return getSkuCostInfo(category, caliber, capacity) !== null;
}

